// Resuelve un codigo/nombre de pais a su alpha-2 canonico, o undefined.
function aAlpha2(codigo: string): string | undefined {
  const bruto = codigo.trim();
  if (!bruto) return undefined;
  const up = bruto.toUpperCase();
  if (up.length === 2 && PAISES_CENTROIDES[up]) return up;
  if (up.length === 3 && ALPHA3_A_ALPHA2[up]) return ALPHA3_A_ALPHA2[up];
  const porNombre = NOMBRE_A_ALPHA2[normaliza(bruto)];
  if (porNombre) return porNombre;
  if (up.length === 2) return up; // alpha-2 sin centroide propio
  return undefined;
}

// Centroide de un pais por alpha-2, alpha-3 o nombre (ingles/espanol).
export function centroidePais(codigo: string): Centroide | undefined {
  if (!codigo) return undefined;
  const a2 = aAlpha2(codigo);
  if (!a2) return undefined;
  const c = PAISES_CENTROIDES[a2];
  if (!c) return undefined;
  return { lat: c.lat, lng: c.lng, nombre: c.nombre };
}

// Indice perezoso de ciudades por nombre normalizado.
let indiceCiudades: Map<string, { nombre: string; pais: string; lat: number; lng: number }[]> | undefined;
function indice(): Map<string, { nombre: string; pais: string; lat: number; lng: number }[]> {
  if (indiceCiudades) return indiceCiudades;
  const m = new Map<string, { nombre: string; pais: string; lat: number; lng: number }[]>();
  for (const c of CIUDADES_CENTROIDES) {
    const k = normaliza(c.nombre);
    const arr = m.get(k);
    if (arr) arr.push(c);
    else m.set(k, [c]);
  }
  indiceCiudades = m;
  return m;
}

// Centroide de una ciudad por nombre; si se da codigoPais prefiere ese pais. undefined si no hay match.
export function centroideCiudad(nombre: string, codigoPais?: string): Centroide | undefined {
  if (!nombre) return undefined;
  const candidatos = indice().get(normaliza(nombre));
  if (!candidatos || candidatos.length === 0) return undefined;
  const a2 = codigoPais ? aAlpha2(codigoPais) : undefined;
  const elegido = (a2 && candidatos.find((c) => c.pais === a2)) || candidatos[0];
  return { lat: elegido.lat, lng: elegido.lng, nombre: elegido.nombre };
}
